"""Comprehensive results table for professor review.

Builds, from docs/all_cells_raw.csv (MobileNetV3 headline, symmetric tightness):
  - paper/tables_results.tex   : booktabs LaTeX, all metrics, per dataset block
  - paper/RESULTS_SUMMARY.md   : human-readable markdown for quick review
  - paired W/T/L scoreboard (LaTeX + md) vs each baseline

All metrics: Macro F1, Weighted F1, Accuracy, ECE, Brier, Flips, In-train Sat%.
Mean +/- std across the symmetric headline cells x seeds. Bold marks the best
method per (dataset, metric). TraLO vs each baseline gets a paired bootstrap p.
"""
from __future__ import annotations

from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent.parent
PAPER = ROOT / "paper"
CSV = ROOT / "docs" / "all_cells_raw.csv"

METHODS = ["tralo", "tralo_bounded", "fioretto_ldf", "hounie_rcl", "danits_lp", "heuristic"]
BASELINES = [m for m in METHODS if m != "tralo"]
LABEL = {"tralo": "TraLO (ours)", "tralo_bounded": "TraLO-bounded",
         "fioretto_ldf": "Fioretto LDF", "hounie_rcl": "Hounie RCL",
         "danits_lp": "Danits LP", "heuristic": "Heuristic"}
# (display, key, higher_is_better, decimals)
METRICS = [("Macro F1", "f1m", True, 3), ("Wtd F1", "f1w", True, 3),
           ("Acc", "acc", True, 3), ("ECE", "ece", False, 3),
           ("Brier", "brier", False, 3), ("Flips", "flips", False, 1),
           ("Sat\\%", "sat", True, 2)]
DS = [("tissuemnist", "TissueMNIST", 4, "synth_group"),
      ("dermmnist", "DermMNIST", 4, "loc_group"),
      ("aider", "AIDER", 0, "synth_group")]


def headline(df, ds, cls, grp):
    """MobileNetV3, symmetric tightness, canonical (cls, grp) for this dataset."""
    return df[(df.ds == ds) & (df.model == "MobileNetV3") & (df.cls == cls)
              & (df.grp == grp) & (df.L == df.G)]


def paired_p(df, ds, cls, grp, metric, higher):
    """Bootstrap p over matched-seed diffs, TraLO vs each baseline."""
    d = headline(df, ds, cls, grp)
    keys = ["tight", "L", "G", "seed"]
    piv = d.pivot_table(index=keys, columns="method", values=metric).dropna(subset=["tralo"])
    out = {}
    rng = np.random.default_rng(0)
    for b in BASELINES:
        if b not in piv.columns:
            out[b] = None; continue
        sub = piv[["tralo", b]].dropna()
        diff = (sub["tralo"] - sub[b]).values if higher else (sub[b] - sub["tralo"]).values
        if len(diff) == 0:
            out[b] = None; continue
        boot = rng.choice(diff, size=(2000, len(diff)), replace=True).mean(axis=1)
        p = 2 * min((boot <= 0).mean(), (boot >= 0).mean())
        out[b] = (diff.mean(), p)
    return out


def fmt(mean, std, dec):
    return f"{mean:.{dec}f}$\\pm${std:.{dec}f}"


def build_latex(df):
    lines = []
    lines.append("% Auto-generated by paper/scripts/build_results_table.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Headline comparison on MobileNetV3 across the five symmetric "
                 "tightness regimes (mean$\\pm$std over tightness$\\times$seeds). "
                 "\\textbf{Bold} = best method per (dataset, metric): highest "
                 "F1/Acc/Sat\\%, lowest ECE/Brier/Flips. TraLO matches the best baseline "
                 "on accuracy metrics while requiring far fewer post-hoc flips and "
                 "satisfying constraints in-training.}")
    lines.append("\\label{tab:results_master}")
    lines.append("\\small\\setlength{\\tabcolsep}{4pt}")
    lines.append("\\begin{tabular}{ll" + "c" * len(METRICS) + "}")
    lines.append("\\toprule")
    lines.append("Dataset & Method & " + " & ".join(m[0] for m in METRICS) + " \\\\")
    for ds, dstitle, cls, grp in DS:
        lines.append("\\midrule")
        d = headline(df, ds, cls, grp)
        # best per metric
        best = {}
        for _, key, higher, _ in METRICS:
            means = {m: d[d.method == m][key].mean() for m in METHODS if not d[d.method == m].empty}
            if not means:
                best[key] = None; continue
            best[key] = (max if higher else min)(means, key=means.get)
        for i, m in enumerate(METHODS):
            dm = d[d.method == m]
            if dm.empty:
                continue
            cells = []
            for disp, key, higher, dec in METRICS:
                mean, std = dm[key].mean(), dm[key].std()
                s = fmt(mean, std, dec)
                if best[key] == m:
                    s = "\\textbf{" + s + "}"
                cells.append(s)
            prefix = f"\\multirow{{6}}{{*}}{{{dstitle}}} " if i == 0 else ""
            lines.append(f"{prefix}& {LABEL[m]} & " + " & ".join(cells) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    (PAPER / "tables_results.tex").write_text("\n".join(lines), encoding="utf-8")
    print("wrote", PAPER / "tables_results.tex")


def build_markdown(df):
    out = ["# Results summary (professor review)\n",
           "MobileNetV3, five symmetric tightness regimes, 4 seeds. "
           "Mean +/- std over tightness x seeds. **Bold** = best per (dataset, metric).\n"]
    for ds, dstitle, cls, grp in DS:
        d = headline(df, ds, cls, grp)
        out.append(f"\n## {dstitle}\n")
        hdr = "| Method | " + " | ".join(m[0].replace("\\%", "%") for m in METRICS) + " |"
        out.append(hdr)
        out.append("|" + "---|" * (len(METRICS) + 1))
        best = {}
        for _, key, higher, _ in METRICS:
            means = {m: d[d.method == m][key].mean() for m in METHODS if not d[d.method == m].empty}
            best[key] = (max if higher else min)(means, key=means.get) if means else None
        for m in METHODS:
            dm = d[d.method == m]
            if dm.empty:
                continue
            cells = []
            for disp, key, higher, dec in METRICS:
                v = f"{dm[key].mean():.{dec}f}"
                if best[key] == m:
                    v = f"**{v}**"
                cells.append(v)
            out.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")
    # paired scoreboard
    out.append("\n## Paired significance: TraLO vs each baseline (Macro F1 & Flips)\n")
    out.append("Bootstrap p over matched seeds. W = TraLO better & p<0.05.\n")
    for ds, dstitle, cls, grp in DS:
        out.append(f"\n### {dstitle}\n")
        out.append("| vs baseline | F1 diff | F1 p | F1 verdict | Flips saved | Flips p | Flips verdict |")
        out.append("|---|---|---|---|---|---|---|")
        f1 = paired_p(df, ds, cls, grp, "f1m", True)
        fl = paired_p(df, ds, cls, grp, "flips", False)
        for b in BASELINES:
            if f1[b] is None:
                continue
            f1d, f1p = f1[b]; fld, flp = fl[b]
            f1v = "**WIN**" if (f1d > 0 and f1p < 0.05) else ("loss" if (f1d < 0 and f1p < 0.05) else "tie")
            flv = "**WIN**" if (fld > 0 and flp < 0.05) else ("loss" if (fld < 0 and flp < 0.05) else "tie")
            out.append(f"| {LABEL[b]} | {f1d:+.4f} | {f1p:.3f} | {f1v} | "
                       f"{fld:+.1f} | {flp:.3f} | {flv} |")
    (ROOT / "docs" / "RESULTS_SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", ROOT / "docs" / "RESULTS_SUMMARY.md")


if __name__ == "__main__":
    df = pd.read_csv(CSV)
    df = df[df.ds != "eurosat"].dropna(subset=["f1m", "flips", "sat"])
    build_latex(df)
    build_markdown(df)
    print("done.")
